namespace TNO.Core.Excel;

/// <summary>
/// ExcelVerticalAlignment enum, the vertical alignment of a cell's content.
/// </summary>
public enum ExcelVerticalAlignment
{
    /// <summary>
    /// Align to the bottom edge of the cell (the spreadsheet default).
    /// </summary>
    Bottom = 0,

    /// <summary>
    /// Align to the top edge of the cell.
    /// </summary>
    Top = 1,

    /// <summary>
    /// Centre vertically within the cell.
    /// </summary>
    Center = 2,
}
